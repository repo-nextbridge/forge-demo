// ★★★ A FORK OF A FORGE SURFACE CARRIES ITS OWN LIST AND ITS OWN GENERATOR — and when the generator cannot
// run, THE REASON IS NAMED, with the file and line that owes the fix.
//
//   node --test bin/fork-codegen.guard.mjs        (or: bash bin/test.sh)
//   FORGE_MONOREPO=~/path/to/forge node --test bin/fork-codegen.guard.mjs
//
// ── ⛔ THE SILENCE THIS ENDS, measured on this bench 2026-09-13 ───────────────────────────────────────────
//
// `src/lib/**/generated/` is a GENERATED surface. Inside the Forge monorepo `pnpm codegen` rewrites it on
// every change and a drift-check reprograms anybody who edits it by hand. In THIS repository's forked vitrine
// it was a PHOTOGRAPH: `storefront-coffee/src/lib/extensions/generated/registry.tsx` still carried the header
// `GENERATED by @forge/codegen from extensions/composition.base.json` — a generator and a list this project
// does not have — and no `gate-registry.tsx` existed beside it at all. So this box could install an app, see
// it enabled in the kernel and its card in the admin, and the page would draw nothing, telling nobody.
//
// The product's answer is `@forgeco/surface-codegen`: a TOOL the fork installs and runs against its own
// `composition.json`. It is in the release (`scripts/publishing/publishable.json`) and `bin/vendor-packages.sh`
// has been writing its tarball into `storefront-coffee/vendor/` for days. ⚠️ AND NOTHING WAS INSTALLING IT:
// the fork pinned it in `overrides`, which npm applies only to a package something else already depends on.
// Measured before this slice — 19 tarballs in `vendor/`, and `node_modules/@forgeco/surface-codegen`
// absent. An `overrides` entry is not a dependency.
//
// ── ★★ WHAT THIS FILE GRADES, AND WHY THE VERDICT IS AN OUTCOME AND NOT A BOOLEAN ────────────────────────
//
// Running the tool is the only thing that proves any of this, so this guard RUNS IT. But on this release the
// tool cannot finish, for reasons that are the PRODUCT's and not patchable from here — so the outcome is
// graded against `UPSTREAM_WALLS` below: every wall is printed on every run, a wall that stops matching is
// RED (it fell — regenerate and commit), and an outcome that is neither clean nor a declared wall is RED
// immediately. Same two safeguards as `bin/front-app-reach.guard.mjs`'s DIVERGENCES, for the same reason: a
// red with nowhere to go gets deleted, and a waiver nobody needs hides the next defect.
//
// ⛔ THE LIST IS DERIVED, NEVER TYPED. The forks come from `bin/forks.mjs`; which surface each is a cut OF
// comes from the release's own `scripts/publishing/surfaces.json`; the command a fork must call comes from the
// `bin` field of the INSTALLED tool. A second fork tomorrow is graded without anybody editing this file.

import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import test from 'node:test';
import { surfaceForks } from './forks.mjs';
import { pinnedCommit, readJson, releaseTree, ROOT } from './release-tree.mjs';

const say = (line) => console.error(`[fork-codegen] ${line}`);

/** The tool, named ONCE — and read out of the release rather than spelled, so a rename upstream arrives here
 *  as a fact. `packages/surface-codegen` is the directory the release keeps it in; its `name` and its `bin`
 *  are what this file compares against. */
const TOOL_DIR = join('packages', 'surface-codegen');

/**
 * ★ THE WALLS THIS BOX CANNOT CLIMB — both are the PRODUCT's and both were measured here on 2026-09-13, on
 * this fork AND on a pristine `pnpm pack:surface storefront` cut installed from the release's own tarballs.
 * A fork installs what the release PUBLISHES; nothing in this repository can change what those tarballs
 * contain, which is the repo boundary this slice stopped at.
 *
 * ★ A WALL IS GRADED WHERE IT IS VISIBLE, and the two are not visible in the same place — which is a rule
 * this file got wrong on its first run and the run said so. `graded: 'outcome'` is a wall that STOPS the
 * generator, recognised by what the run SAYS. `graded: 'ondisk'` is a wall this guard has to ROUTE AROUND in
 * order to run at all (it invokes the module through `node`), so it can never appear in an outcome; it is
 * held by a fact on disk instead, further down. Grading both against the run would have demanded that a wall
 * stop a run this file deliberately prevents it from reaching.
 */
// ⛔ AQUI VIVIAM DOIS MUROS DECLARADOS, E OS DOIS CAÍRAM EM 14/09 (pk35) — a lápide fica porque a razão é o
// achado, não a lista.
//   · `no-shebang` — `packages/surface-codegen/dist/main.js` saía sem `#!`, então o
//     `node_modules/.bin/forge-surface-codegen` era entregue ao `/bin/sh`, que rodava o `import {` como o
//     `import` do ImageMagick e PENDURAVA esperando capturar o mouse no display X, em vez de falhar.
//     ★ O sinal falava de janelas do X sobre um arquivo que só não tinha uma primeira linha.
//   · `kernel-side-exports` — o gerador do lado FRONT exigia os exports do lado KERNEL (`./manifest`, o módulo
//     do driver), que o tarball de front tira DE PROPÓSITO: um front não linka o manifesto do kernel.
// ★★ E o motivo de ninguém os ter visto: o único teste que instala um corte de verdade
// (`packed-surface.guard.test.ts`) morria no `npm install` desde a pk32/p1 — um `EOVERRIDE` — e nunca chegou a
// rodar um build. ⇒ os muros eram invisíveis porque o instrumento morria antes da porta. Tudo isso caiu na
// pk35/p6, e a prova é um corte virgem verde.
//
// ⚠️ A REGRA ABAIXO CONTINUA, e é ela que vale: o gerador tem de RODAR em todo fork de superfície — limpo, ou
// parado por um muro DECLARADO. Com a lista vazia, "limpo" é a única saída aceita, e qualquer falha nova é
// vermelha nomeando o fork. Um muro novo se declara aqui, com `arquivo:linha`, e morre do mesmo jeito.
const UPSTREAM_WALLS = [];

const PINNED = pinnedCommit();
const TREE = PINNED ? releaseTree(PINNED) : { tried: [] };
const FORKS = surfaceForks(TREE);

say(`forks that are a cut of a Forge surface: ${FORKS.map((f) => `${f.dir} (${f.surface.surface})`).join(', ') || 'none'}`);
if (TREE.path) say(`surfaces read from: ${TREE.path} @ ${TREE.head.slice(0, 9)} (${TREE.how})`);
else if (PINNED) {
  say(`⚠️ NOT CHECKED — no Forge checkout at ${PINNED.ref} on this machine.`);
  for (const line of TREE.tried) say(`   tried: ${line}`);
  say('   set FORGE_MONOREPO=<the release\'s checkout>: without it nothing here knows which fork is a cut of');
  say('   which surface, and the tool the release ships cannot be named.');
}
for (const wall of UPSTREAM_WALLS) say(`★ UPSTREAM WALL declared: ${wall.id} — ${wall.why.slice(0, 110)}…`);

/** The release's own name for the tool and for the command it links. Never spelled here. */
function tool() {
  if (!TREE.path) return null;
  const manifest = join(TREE.path, TOOL_DIR, 'package.json');
  if (!existsSync(manifest)) return null;
  const pkg = readJson(manifest);
  const bin = Object.keys(pkg.bin ?? {})[0];
  return bin ? { name: pkg.name, bin } : null;
}

const TOOL = tool();
if (TOOL) say(`the release ships ${TOOL.name}, linking \`${TOOL.bin}\``);

/** What one fork installed of the tool, or null — `NOT CHECKED` material, never a silent pass. */
const installedTool = (fork) => {
  const dir = join(fork.path, 'node_modules', ...(TOOL?.name ?? '').split('/'));
  return TOOL && existsSync(join(dir, 'package.json')) ? dir : null;
};

// ── ⛔ the premises. Every verdict below iterates a list; a list that lost its subject would be green ─────

test('⛔ this box owns at least one fork that is a CUT of a Forge surface', (t) => {
  if (!TREE.path) {
    t.skip('no Forge checkout on this machine — see the NOT CHECKED lines above');
    return;
  }
  assert.ok(
    FORKS.length > 0,
    'no directory of this repository carries the package name of a packed Forge surface. Either the forks ' +
      'were renamed or `scripts/publishing/surfaces.json` stopped naming them — and every rule below would ' +
      'then be true about nothing',
  );
  assert.ok(TOOL, `${TOOL_DIR} of the release declares no \`bin\`, so no fork has a command to call`);
});

// ── ★ the LIST: a fork that cannot say what it composes cannot derive anything ────────────────────────────

test('★★ every surface fork carries its OWN composition list, naming the front it is a cut of', (t) => {
  if (!TREE.path) {
    t.skip('no Forge checkout on this machine — see the NOT CHECKED lines above');
    return;
  }
  for (const fork of FORKS) {
    const file = join(fork.path, 'composition.json');
    assert.ok(
      existsSync(file),
      `${fork.dir} has no composition.json, so everything under its \`src/lib/**/generated/\` is a ` +
        'PHOTOGRAPH of the tree it was cut from — it can install an app, enable it in the kernel, show its ' +
        'card in the admin, and draw nothing. A front cut from a Forge release is born with one.',
    );
    const list = readJson(file);
    assert.equal(
      list.surface,
      fork.surface.surface,
      `${fork.dir}/composition.json says it is the "${list.surface}" front; the release says this project ` +
        `(${fork.surface.packedName}) is a cut of "${fork.surface.surface}". That field decides which ` +
        'registries the tool writes, so a wrong one writes the other front\'s files or none at all',
    );
    // ⚠️ THE ANTI-VACUUM FLOOR, and it is the overlay's own (templates/surfaces/*/src/extension-wiring.test.ts):
    // a list with no apps makes every generated registry empty BY CONSTRUCTION, and a drift check over it is a
    // green light on exactly the state it exists to catch.
    assert.ok(
      Array.isArray(list.apps) && list.apps.length > 0,
      `${fork.dir}/composition.json lists no apps, so its generated registries are empty by construction and ` +
        'the check below would prove nothing',
    );
    say(`${fork.dir}: composes ${list.apps.length} app(s) as the "${list.surface}" front`);
  }
});

test('★★ …and it carries the TOOL as a dependency — an `overrides` entry installs nothing', (t) => {
  if (!TREE.path || !TOOL) {
    t.skip('no Forge checkout on this machine — see the NOT CHECKED lines above');
    return;
  }
  for (const fork of FORKS) {
    const manifest = readJson(join(fork.path, 'package.json'));
    const declared = { ...manifest.dependencies, ...manifest.devDependencies };
    assert.ok(
      Object.hasOwn(declared, TOOL.name),
      `${fork.dir}/package.json does not depend on ${TOOL.name}. ⚠️ An \`overrides\` entry is NOT a ` +
        'dependency: npm applies it to a package something already depends on, so the tarball sits in ' +
        `vendor/ and \`npm install\` brings nothing. Measured on this fork before pk35/d3.`,
    );
    assert.equal(
      manifest.scripts?.codegen,
      TOOL.bin,
      `${fork.dir}/package.json has no \`codegen\` script calling \`${TOOL.bin}\` — the command the release ` +
        'links. A tool only a README mentions has exactly the lifetime of the photograph it replaces',
    );
  }
});

// ── ★★★ the VERDICT: the tool is RUN, and its outcome is graded against the declared walls ────────────────

test('★★★ the generator RUNS in every surface fork — clean, or stopped by a DECLARED upstream wall', (t) => {
  if (!TREE.path || !TOOL) {
    t.skip('no Forge checkout on this machine — see the NOT CHECKED lines above');
    return;
  }
  const graded = [];
  const matched = new Set();
  for (const fork of FORKS) {
    const dir = installedTool(fork);
    if (!dir) {
      say(`${fork.dir}: NOT CHECKED — ${TOOL.name} is not installed. \`bash bin/install-storefront.sh ${fork.dir}\``);
      continue;
    }
    graded.push(fork.dir);

    // ⚠️ INVOKED THROUGH `node`, DELIBERATELY. The linked command is not executable on this release (see the
    // `no-shebang` wall); running the link would measure the shell's opinion of an ESM file, and on a
    // workstation with an X server it HANGS rather than failing. The module is what this rule is about.
    const entry = join(dir, readJson(join(dir, 'package.json')).bin[TOOL.bin]);
    let outcome = 'clean';
    try {
      const stdout = execFileSync(process.execPath, [entry, '--check'], {
        cwd: fork.path,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'pipe'],
        timeout: 120_000,
      });
      say(`${fork.dir}: ${stdout.trim()}`);
    } catch (error) {
      outcome = `${error.stderr ?? ''}${error.stdout ?? ''}${error.message ?? ''}`;
    }

    const wall = UPSTREAM_WALLS.find((w) => w.graded === 'outcome' && w.match(outcome));
    if (wall) {
      matched.add(wall);
      say(`${fork.dir}: stopped by the declared wall "${wall.id}" — the fix is upstream, see the top of this file`);
      continue;
    }
    assert.equal(
      outcome,
      'clean',
      `${fork.dir}: \`${TOOL.bin} --check\` failed for a reason this box has NOT declared:\n${outcome}\n` +
        'Either a generated file disagrees with composition.json — then run `npm run codegen` in that fork ' +
        'and commit what it writes — or a NEW wall appeared, and it belongs in UPSTREAM_WALLS at the top of ' +
        'this file with the file and line that owes the fix.',
    );
  }

  // ★★ NOT CHECKED, NOT RED — the posture every other rule in this directory already has (pk38/d9).
  //
  // ⛔ THIS WAS AN `assert.ok(graded.length > 0)`, AND IT CONTRADICTED THE DOCTRINE ONE FILE OVER: "a machine
  // with no Forge checkout is told NOT CHECKED, never quietly passed … on a dev machine that is the right
  // answer, and it must stay; the STRICT mode is what turns a skip into a failure" (bin/test.sh). An absent
  // tool is exactly that kind of absence — a fork's `node_modules/` is gitignored, so EVERY freshly born
  // worktree of this repository has none — and grading it red here meant no newborn worktree could ever reach
  // a green run, for a reason that says nothing about the code in it. Three slices met that red in one day
  // and had to report that they had proven nothing.
  //
  // ⚠️ AND NOTHING IS LOST, because the skip is graded elsewhere: `FORGE_STRICT_CHECKS=1 bash bin/test.sh`
  // reads the run's own `ℹ skipped` line and refuses to call a run green that reported instead of grading. A
  // pipeline gets the red; a workstation gets the sentence that says what would let it run.
  if (graded.length === 0) {
    t.skip(
      `NOT CHECKED — no fork has ${TOOL.name} on disk, so nothing was generated and nothing was compared. ` +
        'The line above names the install for each fork; give the runner one and this rule runs.',
    );
    return;
  }

  // ⚠️ THE STALE WALL IS THE POINT OF THE LIST, and it is what makes the arrangement temporary: the day the
  // product ships the one-line fix, this goes RED and names the slice that follows.
  const gone = UPSTREAM_WALLS.filter((w) => w.graded === 'outcome' && !matched.has(w)).map((w) => w.id);
  assert.deepEqual(
    gone,
    [],
    `${gone.length} declared upstream wall(s) no longer stop the generator: ${gone.join(', ')}. THE WALL ` +
      'FELL — this fork can now regenerate its own surfaces. Run `npm run codegen` in it, commit the ' +
      'generated files, put `forge-surface-codegen` back in front of its `build` and `test` scripts, and ' +
      'delete the entry from UPSTREAM_WALLS.',
  );
});

test('★ the `no-shebang` wall is a FACT on disk, not only a message — the bin cannot be exec\'d', (t) => {
  if (!TREE.path || !TOOL) {
    t.skip('no Forge checkout on this machine — see the NOT CHECKED lines above');
    return;
  }
  const wall = UPSTREAM_WALLS.find((w) => w.id === 'no-shebang');
  if (!wall) {
    say('the `no-shebang` wall is gone from the list — nothing to state mechanically');
    return;
  }
  let checked = 0;
  for (const fork of FORKS) {
    const dir = installedTool(fork);
    if (!dir) continue;
    const entry = join(dir, readJson(join(dir, 'package.json')).bin[TOOL.bin]);
    const head = readFileSync(entry, 'utf8').slice(0, 2);
    checked += 1;
    assert.notEqual(
      head,
      '#!',
      `${entry} now starts with a shebang, so \`${TOOL.bin}\` is executable as a command and the ` +
        '`no-shebang` wall above is stale. Delete it, and stop routing this guard through `node`.',
    );
    say(`${fork.dir}: the linked command starts with ${JSON.stringify(head)}, not "#!" — /bin/sh would run it`);
  }
  // Same posture as the rule above, for the same reason: an uninstalled fork is an absence this machine can
  // report, never a verdict about the wall.
  if (checked === 0) t.skip('NOT CHECKED — no fork had the tool on disk, so this rule read no file at all');
});

// A fork of ROOT is what every path above is relative to; naming it once keeps this file honest about where
